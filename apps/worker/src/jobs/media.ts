import { createMediaAsset, getMediaAsset, touchProject, updateMediaAsset, updateScript, type MediaAsset, type MediaKind } from "@studio/database";
import { refitVisuals, relayoutNarration } from "./voice";
import { extractFilmstrip, extractThumbnail, extractWaveform, getStorage, probeMedia, projectKey, safeFileName } from "@studio/media";
import type { JobContext } from "../context";

/** Storage key for a derived file (waveform, thumbnail, filmstrip). */
const derivedKey = (projectId: string, assetId: string, suffix: string) => projectKey(projectId, "derived", `${assetId}.${suffix}`);

/**
 * Inspect a stored file and create everything the editor needs to show it:
 * duration and size (ffprobe), a waveform for sound, a thumbnail for
 * pictures and video, and a filmstrip for video clips on the timeline.
 */
export async function processAsset(assetId: string): Promise<MediaAsset> {
  const asset = await getMediaAsset(assetId);
  const storage = getStorage();
  const file = await storage.localPath(asset.storageKey);
  try {
    const info = await probeMedia(file);
    const patch: Parameters<typeof updateMediaAsset>[1] = {
      durationSeconds: asset.kind === "image" ? null : info.durationSeconds,
      width: info.width,
      height: info.height,
    };
    if ((asset.kind === "audio" || asset.kind === "video") && !info.durationSeconds) {
      throw new Error("This file has no playable length.");
    }
    if (asset.kind === "audio" && !info.hasAudio) throw new Error("This file has no sound in it.");
    if ((asset.kind === "audio" || (asset.kind === "video" && info.hasAudio)) && info.durationSeconds) {
      const waveform = await extractWaveform(file);
      const key = derivedKey(asset.projectId, asset.id, "waveform.json");
      await storage.put(key, Buffer.from(JSON.stringify(waveform)));
      patch.waveformKey = key;
    }
    if (asset.kind === "image" || asset.kind === "video" || asset.kind === "render") {
      const key = derivedKey(asset.projectId, asset.id, "thumb.jpg");
      await extractThumbnail(file, await storage.localPath(key).then(ensureDir), {
        atSeconds: asset.kind === "image" ? undefined : Math.min(1, (info.durationSeconds ?? 0) / 2),
      });
      patch.thumbnailKey = key;
    }
    if (asset.kind === "video" && info.durationSeconds) {
      const key = derivedKey(asset.projectId, asset.id, "strip.jpg");
      patch.filmstripFrames = await extractFilmstrip(file, await storage.localPath(key).then(ensureDir), info.durationSeconds);
      patch.filmstripKey = key;
    }
    return await updateMediaAsset(asset.id, { ...patch, status: "ready", error: null });
  } catch (error) {
    const message = error instanceof Error ? error.message : "This file couldn't be read.";
    await updateMediaAsset(asset.id, { status: "failed", error: message });
    throw error;
  }
}

async function ensureDir(file: string): Promise<string> {
  const { mkdir } = await import("node:fs/promises");
  const path = await import("node:path");
  await mkdir(path.dirname(file), { recursive: true });
  return file;
}

export async function runMediaProcess(ctx: JobContext, input: { assetId: string; shotId: string | null }): Promise<Record<string, unknown>> {
  await ctx.progress(0.1, "Reading the file");
  const asset = await processAsset(input.assetId);
  // Uploaded narration for a scene replaces that scene's voice-over.
  if (asset.kind === "audio" && asset.role === "narration" && asset.sceneId) {
    await ctx.progress(0.8, "Placing narration on the timeline");
    await updateScript(ctx.projectId, (s) => ({
      ...s,
      scenes: s.scenes.map((sc) => (sc.id === asset.sceneId ? { ...sc, narrationAssetId: asset.id } : sc)),
    }));
    await relayoutNarration(ctx.projectId);
  }
  // An uploaded picture/video chosen for a planned shot.
  if (input.shotId && (asset.kind === "image" || asset.kind === "video")) {
    await ctx.progress(0.8, "Placing the picture on the timeline");
    const { script } = await updateScript(ctx.projectId, (s) => ({
      ...s,
      scenes: s.scenes.map((sc) => ({ ...sc, shots: sc.shots.map((sh) => (sh.id === input.shotId ? { ...sh, assetId: asset.id } : sh)) })),
    }));
    await refitVisuals(ctx.projectId, script);
  }
  if (asset.kind === "image" && asset.thumbnailKey) await touchProject(ctx.projectId, "Picture uploaded", { thumbnailKey: asset.thumbnailKey });
  return { assetId: asset.id, durationSeconds: asset.durationSeconds };
}

/** Save generated bytes as a project asset and process it straight away. */
export async function storeGenerated(input: {
  projectId: string;
  kind: MediaKind;
  role: string;
  name: string;
  data: Buffer;
  extension: string;
  mimeType: string;
  provider: string;
  prompt?: string | null;
  sceneId?: string | null;
  generationSettings?: Record<string, unknown>;
}): Promise<MediaAsset> {
  const storage = getStorage();
  const fileName = `${Date.now()}-${safeFileName(input.name, input.role)}`.replace(/\.[a-z0-9]+$/i, "") + `.${input.extension}`;
  const key = projectKey(input.projectId, input.kind === "audio" ? "audio" : input.kind === "image" ? "images" : "video", fileName);
  const { sizeBytes } = await storage.put(key, input.data);
  const asset = await createMediaAsset({
    projectId: input.projectId,
    kind: input.kind,
    origin: "generated",
    role: input.role,
    name: input.name,
    storageKey: key,
    mimeType: input.mimeType,
    sizeBytes,
    provider: input.provider,
    prompt: input.prompt ?? null,
    sceneId: input.sceneId ?? null,
    generationSettings: input.generationSettings ?? {},
  });
  const ready = await processAsset(asset.id);
  if (input.kind === "image" && ready.thumbnailKey) await touchProject(input.projectId, "Pictures created", { thumbnailKey: ready.thumbnailKey });
  return ready;
}
